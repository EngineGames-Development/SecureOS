#include "include/font.h"
#include "include/kernel.h"

unsigned char font_bitmap[256][16] = {
    ['S'] = {0x3C, 0x66, 0x60, 0x3C, 0x06, 0x66, 0x3C, 0x00},
    ['E'] = {0x7E, 0x60, 0x60, 0x7C, 0x60, 0x60, 0x7E, 0x00},
    ['C'] = {0x3C, 0x66, 0x60, 0x60, 0x60, 0x66, 0x3C, 0x00},
    ['U'] = {0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00},
    ['R'] = {0x7C, 0x66, 0x66, 0x7C, 0x6C, 0x66, 0x66, 0x00},
    ['O'] = {0x3C, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00},
    ['T'] = {0x7E, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00},
    ['A'] = {0x18, 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x00},
    ['N'] = {0x66, 0x76, 0x7E, 0x6E, 0x66, 0x66, 0x66, 0x00},
    ['G'] = {0x3C, 0x66, 0x60, 0x6C, 0x66, 0x66, 0x3C, 0x00},
    ['X'] = {0x66, 0x66, 0x3C, 0x18, 0x3C, 0x66, 0x66, 0x00},
    [' '] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}};

void draw_char(int x, int y, char c, unsigned int color) {
  for (int i = 0; i < 16; i++) {
    unsigned char byte = font_bitmap[(unsigned char)c][i];
    for (int bit = 0; bit < 8; bit++) {
      if (byte & (0x80 >> bit)) {
        draw_pixel(x + bit, y + i, color);
      }
    }
  }
}

void draw_string(int x, int y, const char *str, unsigned int color) {
  int i = 0;
  while (str[i] != '\0') {
    draw_char(x + (i * 8), y, str[i], color);
    i++;
  }
}
